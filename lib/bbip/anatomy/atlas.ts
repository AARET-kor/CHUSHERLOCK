import type { DepthKey, LayerKey, ProcedureCategory, RiskLevel, ViewKey } from "./layers";

// Curated anatomy atlas for the BBIP map. Positions are hand-authored from
// standard facial anatomy — the model never produces coordinates. Every
// structure ships as a draft: the doctor reviews it and fills reviewedBy /
// reviewedAt here, which removes the "원장 검토 전 초안" badge.
//
// Coordinates: viewBox 240×300, front view, midline x=120. Structures are
// drawn on the viewer's right (patient's left, x>120) and mirrored in the
// front view; the oblique and lateral views are projected from these points
// (lib/bbip/anatomy/geometry.ts) unless `shapes.oblique` / `shapes.lateral`
// are given explicitly. Landmarks: medial canthus (136,126), lateral canthus
// (176,124), infraorbital rim y≈140, nasion (120,122), nasal tip (120,176),
// alar base (139,178), oral commissure (148,212), menton (120,272),
// mandibular angle ≈ (196,232), tragus (205,150).

export type Pt = readonly [number, number];

export type Shape =
  | { kind: "line"; pts: Pt[] }
  | { kind: "area"; pts: Pt[] }
  | { kind: "point"; at: Pt }
  | { kind: "vector"; from: Pt; to: Pt };

export interface AtlasStructure {
  id: string;
  ko: string;
  en: string;
  layer: LayerKey;
  /** Layers the structure runs in, superficial → deep. */
  depths: DepthKey[];
  depthNote: string;
  risk: RiskLevel;
  riskNote: string;
  /** Course / location relative to surface landmarks. */
  course: string;
  safeTechnique: string;
  /** Terms used to match the doctor's notes and figure captions. */
  keywords: string[];
  shapes: Partial<Record<ViewKey, Shape[]>>;
  /** Line points are authored in flow order (origin → where it goes). Set
   * "reverse" when a line was drawn against its flow. */
  flow?: "reverse";
  /** Entry points only: the procedures this entry applies to. */
  entryFor?: ProcedureCategory[];
  source: string;
  reviewedBy?: string;
  reviewedAt?: string;
}

